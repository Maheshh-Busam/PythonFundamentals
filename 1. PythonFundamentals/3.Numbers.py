# Arithmetic operators

# + 	Addition
# -	  Subtraction
# *	  Multiplication
# /	  Division
# //	Floor division
# %	  Remainder
# **	Power

a = 10
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)
print("----")

